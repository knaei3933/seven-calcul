import type { SqlClient } from "@/lib/db";
import { projectPortalQuote, type PortalQuoteProjection } from "@/lib/portal/quote-projection";

export type PortalQuoteOwnerDomain = "kanei";

interface PortalQuoteReadRow {
  public_id: string;
  quotation_number: string;
  issue_date: string;
  valid_until: string;
  customer_name: string;
  customer_contact: string;
  product_name: string;
  size_summary: string;
  quantity: string;
  price_per_piece: string;
  subtotal: string;
  tax: string;
  grand_total: string;
  delivery_date: string;
  payment_terms: string;
  notes: string;
  created_at: string;
}

const SQLITE_SCHEMA = `
    CREATE TABLE IF NOT EXISTS portal_quote_mappings (
      id INTEGER PRIMARY KEY AUTOINCREMENT,
      public_id TEXT NOT NULL UNIQUE,
      quotation_id INTEGER NOT NULL UNIQUE,
      portal_user_id INTEGER NOT NULL,
      owner_domain TEXT NOT NULL CHECK(owner_domain IN ('kanei')),
      customer_code TEXT NOT NULL,
      source TEXT NOT NULL CHECK(source IN ('customer_portal')),
      idempotency_key TEXT NOT NULL,
      request_fingerprint TEXT NOT NULL,
      response_json TEXT NOT NULL,
      created_at TEXT NOT NULL,
      updated_at TEXT NOT NULL,
      UNIQUE(owner_domain, portal_user_id, idempotency_key)
    );
    CREATE INDEX IF NOT EXISTS idx_portal_quote_mappings_owner
      ON portal_quote_mappings(portal_user_id, created_at DESC);
`;

const POSTGRES_SCHEMA = `
    CREATE TABLE IF NOT EXISTS portal_quote_mappings (
      id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      public_id TEXT NOT NULL UNIQUE,
      quotation_id INTEGER NOT NULL UNIQUE,
      portal_user_id INTEGER NOT NULL,
      owner_domain TEXT NOT NULL CHECK(owner_domain IN ('kanei')),
      customer_code TEXT NOT NULL,
      source TEXT NOT NULL CHECK(source IN ('customer_portal')),
      idempotency_key TEXT NOT NULL,
      request_fingerprint TEXT NOT NULL,
      response_json TEXT NOT NULL,
      created_at TEXT NOT NULL,
      updated_at TEXT NOT NULL,
      UNIQUE(owner_domain, portal_user_id, idempotency_key)
    );
    CREATE INDEX IF NOT EXISTS idx_portal_quote_mappings_owner
      ON portal_quote_mappings(portal_user_id, created_at DESC);
`;

let schemaReady: Promise<SqlClient> | null = null;

async function getDatabase(): Promise<SqlClient> {
  schemaReady ??= (async () => {
    const { getDatabaseForTest } = await import("@/lib/quotation-store");
    const db = await getDatabaseForTest();
    await db.exec(db.dialect === "postgres" ? POSTGRES_SCHEMA : SQLITE_SCHEMA);
    return db;
  })().catch((error) => {
    schemaReady = null;
    throw error;
  });
  return schemaReady;
}

export async function resetPortalQuoteReadStoreForTest(): Promise<void> {
  schemaReady = null;
}

function portalUserScope(input: {
  portalUserId: number;
  ownerDomain: PortalQuoteOwnerDomain;
  customerCode: string;
}): [string, unknown[]] {
  return [`
    portal_quote_mappings.portal_user_id = ?
    AND portal_quote_mappings.owner_domain = ?
    AND portal_quote_mappings.customer_code = ?
    AND portal_quote_mappings.source = 'customer_portal'
  `, [input.portalUserId, input.ownerDomain, input.customerCode]];
}

function safeQuoteSelection(): string {
  // Mapping-first join: quotations are reachable only through owner-scoped
  // portal mappings. The numeric quotation id is never selected or accepted.
  return `
    SELECT portal_quote_mappings.public_id,
           quotations.quotation_number,
           quotations.issue_date,
           quotations.valid_until,
           quotations.customer_name,
           quotations.customer_contact,
           quotations.product_name,
           quotations.size_summary,
           quotations.quantity,
           quotations.price_per_piece,
           quotations.subtotal,
           quotations.tax,
           quotations.grand_total,
           quotations.delivery_date,
           quotations.payment_terms,
           quotations.notes,
           portal_quote_mappings.created_at
    FROM portal_quote_mappings
      INNER JOIN quotations ON quotations.id = portal_quote_mappings.quotation_id
  `;
}

function isPublicId(value: string): boolean {
  return /^[0-9a-f]{8}-[0-9a-f]{4}-[1-5][0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$/i.test(value);
}

function readRow(row: PortalQuoteReadRow, now: Date): PortalQuoteProjection {
  if (!isPublicId(row.public_id)) throw new Error("portal_quote_mapping_invalid");
  return projectPortalQuote({
    publicId: row.public_id,
    quotationNumber: row.quotation_number,
    issueDate: row.issue_date,
    validUntil: row.valid_until,
    customerName: row.customer_name,
    customerContact: row.customer_contact,
    productName: row.product_name,
    sizeSummary: row.size_summary,
    quantity: row.quantity,
    pricePerPiece: row.price_per_piece,
    subtotal: row.subtotal,
    tax: row.tax,
    grandTotal: row.grand_total,
    deliveryDate: row.delivery_date,
    paymentTerms: row.payment_terms,
    notes: row.notes,
    createdAt: row.created_at,
  }, now);
}

export async function findOwnPortalQuote(input: {
  portalUserId: number;
  ownerDomain: PortalQuoteOwnerDomain;
  customerCode: string;
  publicId: string;
  now: Date;
}): Promise<PortalQuoteProjection | null> {
  if (!isPublicId(input.publicId)) return null;
  const db = await getDatabase();
  const [scope, scopeArguments] = portalUserScope(input);
  const row = await db.get<PortalQuoteReadRow>(
    `${safeQuoteSelection()} WHERE ${scope} AND portal_quote_mappings.public_id = ?`,
    [...scopeArguments, input.publicId],
  );
  return row ? readRow(row, input.now) : null;
}

export interface PortalQuotePage {
  quotes: PortalQuoteProjection[];
  nextCursor: string | null;
}

export async function listOwnPortalQuotes(input: {
  portalUserId: number;
  ownerDomain: PortalQuoteOwnerDomain;
  customerCode: string;
  limit: number;
  cursor?: { createdAt: string; publicId: string };
  now: Date;
}): Promise<PortalQuotePage> {
  const db = await getDatabase();
  const [scope, scopeArguments] = portalUserScope(input);
  let cursorCondition = "";
  const cursorArguments: Array<string> = [];
  if (input.cursor) {
    cursorCondition = `
      AND (portal_quote_mappings.created_at < ?
        OR (portal_quote_mappings.created_at = ?
          AND portal_quote_mappings.public_id < ?))`;
    cursorArguments.push(input.cursor.createdAt, input.cursor.createdAt, input.cursor.publicId);
  }
  const rows = await db.all<PortalQuoteReadRow>(
    `${safeQuoteSelection()} WHERE ${scope}${cursorCondition}
     ORDER BY portal_quote_mappings.created_at DESC, portal_quote_mappings.public_id DESC
     LIMIT ?`,
    [...scopeArguments, ...cursorArguments, input.limit + 1],
  );
  const hasMore = rows.length > input.limit;
  const pageRows = hasMore ? rows.slice(0, input.limit) : rows;
  const lastRow = pageRows.at(-1);
  return {
    quotes: pageRows.map((row) => readRow(row, input.now)),
    nextCursor: hasMore && lastRow
      ? encodeCursor({ createdAt: lastRow.created_at, publicId: lastRow.public_id })
      : null,
  };
}

export function encodeCursor(cursor: { createdAt: string; publicId: string }): string {
  return Buffer.from(JSON.stringify(cursor), "utf8").toString("base64url");
}

export function decodeCursor(value: string): { createdAt: string; publicId: string } | null {
  try {
    const parsed: unknown = JSON.parse(Buffer.from(value, "base64url").toString("utf8"));
    if (!parsed || typeof parsed !== "object" || Array.isArray(parsed)) return null;
    const cursor = parsed as Record<string, unknown>;
    if (Object.keys(cursor).length !== 2) return null;
    if (typeof cursor.createdAt !== "string" || typeof cursor.publicId !== "string") return null;
    if (Number.isNaN(Date.parse(cursor.createdAt)) || !isPublicId(cursor.publicId)) return null;
    return { createdAt: cursor.createdAt, publicId: cursor.publicId };
  } catch {
    return null;
  }
}
