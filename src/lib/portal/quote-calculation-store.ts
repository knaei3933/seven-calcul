import { randomUUID } from "node:crypto";
import { getSqlClient, isUniqueViolation, type SqlClient } from "@/lib/db";
import type { QuotationRecordInput } from "@/lib/quotation-shared";

export type PortalQuoteOwnerDomain = "kanei";

export interface PortalQuoteMapping {
  publicId: string;
  quotationNumber: string;
  quotationId: number;
  portalUserId: number;
  ownerDomain: PortalQuoteOwnerDomain;
  customerCode: string;
  source: "customer_portal";
  idempotencyKey: string;
  requestFingerprint: string;
  response: Record<string, unknown>;
}

export class PortalQuoteIdempotencyConflictError extends Error {
  constructor() {
    super("portal_quote_idempotency_conflict");
    this.name = "PortalQuoteIdempotencyConflictError";
  }
}

let schemaReady: Promise<SqlClient> | null = null;

const SQLITE_SCHEMA = `
    CREATE TABLE IF NOT EXISTS portal_quote_mappings (
      id INTEGER PRIMARY KEY AUTOINCREMENT,
      public_id TEXT NOT NULL UNIQUE,
      quotation_id INTEGER NOT NULL UNIQUE,
      portal_user_id INTEGER NOT NULL,
      owner_domain TEXT NOT NULL CHECK(owner_domain IN ('kanei')),
      customer_code TEXT NOT NULL,
      source TEXT NOT NULL CHECK(source IN ('customer_portal')),
      idempotency_key TEXT NOT NULL,
      request_fingerprint TEXT NOT NULL,
      response_json TEXT NOT NULL,
      created_at TEXT NOT NULL,
      updated_at TEXT NOT NULL,
      UNIQUE(owner_domain, portal_user_id, idempotency_key)
    );
    CREATE INDEX IF NOT EXISTS idx_portal_quote_mappings_owner
      ON portal_quote_mappings(portal_user_id, created_at DESC);
`;

const POSTGRES_SCHEMA = `
    CREATE TABLE IF NOT EXISTS portal_quote_mappings (
      id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      public_id TEXT NOT NULL UNIQUE,
      quotation_id INTEGER NOT NULL UNIQUE,
      portal_user_id INTEGER NOT NULL,
      owner_domain TEXT NOT NULL CHECK(owner_domain IN ('kanei')),
      customer_code TEXT NOT NULL,
      source TEXT NOT NULL CHECK(source IN ('customer_portal')),
      idempotency_key TEXT NOT NULL,
      request_fingerprint TEXT NOT NULL,
      response_json TEXT NOT NULL,
      created_at TEXT NOT NULL,
      updated_at TEXT NOT NULL,
      UNIQUE(owner_domain, portal_user_id, idempotency_key)
    );
    CREATE INDEX IF NOT EXISTS idx_portal_quote_mappings_owner
      ON portal_quote_mappings(portal_user_id, created_at DESC);
`;

interface MappingRow {
  public_id: string;
  quotation_number: string;
  quotation_id: number;
  portal_user_id: number;
  owner_domain: string;
  customer_code: string;
  source: string;
  idempotency_key: string;
  request_fingerprint: string;
  response_json: string;
}

async function getDatabase(): Promise<SqlClient> {
  schemaReady ??= (async () => {
    const { getDatabaseForTest } = await import("@/lib/quotation-store");
    const db = await getDatabaseForTest();
    await db.exec(db.dialect === "postgres" ? POSTGRES_SCHEMA : SQLITE_SCHEMA);
    return db;
  })().catch((error) => {
    schemaReady = null;
    throw error;
  });
  return schemaReady;
}

export async function getPortalQuoteDatabaseForTest(): Promise<SqlClient> {
  return getDatabase();
}

export async function initializePortalQuoteMappingSchema(): Promise<void> {
  await getDatabase();
}

export async function resetPortalQuoteStoreForTest(): Promise<void> {
  schemaReady = null;
  const { resetSqlClientForTest } = await import("@/lib/db");
  await resetSqlClientForTest();
}

function mapMapping(row: MappingRow): PortalQuoteMapping {
  if (
    row.owner_domain !== "kanei" || row.source !== "customer_portal"
    || !/^[0-9a-f-]{36}$/i.test(row.public_id)
  ) throw new Error("portal_quote_mapping_invalid");
  const response = JSON.parse(row.response_json) as unknown;
  if (!response || typeof response !== "object" || Array.isArray(response)) {
    throw new Error("portal_quote_response_invalid");
  }
  return {
    publicId: row.public_id,
    quotationNumber: row.quotation_number,
    quotationId: Number(row.quotation_id),
    portalUserId: Number(row.portal_user_id),
    ownerDomain: "kanei",
    customerCode: row.customer_code,
    source: "customer_portal",
    idempotencyKey: row.idempotency_key,
    requestFingerprint: row.request_fingerprint,
    response: response as Record<string, unknown>,
  };
}

function mappingSelection(): string {
  return `
    SELECT portal_quote_mappings.public_id,
           quotations.quotation_number,
           portal_quote_mappings.quotation_id,
           portal_quote_mappings.portal_user_id,
           portal_quote_mappings.owner_domain,
           portal_quote_mappings.customer_code,
           portal_quote_mappings.source,
           portal_quote_mappings.idempotency_key,
           portal_quote_mappings.request_fingerprint,
           portal_quote_mappings.response_json
    FROM portal_quote_mappings
      INNER JOIN quotations ON quotations.id = portal_quote_mappings.quotation_id
  `;
}

export async function findPortalQuoteMapping(input: {
  portalUserId: number;
  ownerDomain: PortalQuoteOwnerDomain;
  idempotencyKey: string;
}): Promise<PortalQuoteMapping | null> {
  const db = await getDatabase();
  const row = await db.get<MappingRow>(
    `${mappingSelection()}
     WHERE portal_quote_mappings.owner_domain = ?
       AND portal_quote_mappings.portal_user_id = ?
       AND portal_quote_mappings.idempotency_key = ?`,
    [input.ownerDomain, input.portalUserId, input.idempotencyKey],
  );
  return row ? mapMapping(row) : null;
}

function insertPortalQuotationSql(): string {
  return `
    INSERT INTO quotations (
      quotation_number,status,issue_date,valid_until,customer_name,customer_contact,product_name,size_summary,
      quantity,filling_cost_per_piece,film_cost_per_piece,film_meter_price,film_order_length_m,target_margin,
      tax_rate_percent,price_per_piece,subtotal,tax,grand_total,delivery_date,payment_terms,notes,
      calculation_version,result_hash,payload_json,created_at,updated_at,created_by,updated_by
    ) VALUES (?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?)
  `;
}

function allocateQuotationNumber(
  usedNumbers: Array<{ quotation_number: string }>,
  issueDate: string,
): string {
  const month = new Date(issueDate).toLocaleDateString("en-CA", { timeZone: "Asia/Tokyo" })
    .slice(0, 7).replace("-", "");
  const prefix = `KT-${month}-`;
  const usedSuffixes = new Set(usedNumbers.map((row) => {
    const match = /^KT-\d{6}-(\d+)$/.exec(row.quotation_number);
    return match ? Number(match[1]) : 0;
  }).filter((suffix) => suffix > 0));
  let suffix = 1;
  while (usedSuffixes.has(suffix)) suffix += 1;
  return `${prefix}${String(suffix).padStart(3, "0")}`;
}

export async function createPortalQuoteWithMapping(input: {
  quotation: Omit<QuotationRecordInput, "quotationNumber">;
  actorId: number;
  portalUserId: number;
  ownerDomain: PortalQuoteOwnerDomain;
  customerCode: string;
  idempotencyKey: string;
  requestFingerprint: string;
  buildResponse: (identifiers: { publicId: string; quotationNumber: string }) => Record<string, unknown>;
}): Promise<PortalQuoteMapping> {
  const db = await getDatabase();
  for (let attempt = 0; attempt < 5; attempt += 1) {
    try {
      return await db.transaction(async (tx): Promise<PortalQuoteMapping> => {
        const existingRow = await tx.get<MappingRow>(
          `${mappingSelection()}
           WHERE portal_quote_mappings.owner_domain = ?
             AND portal_quote_mappings.portal_user_id = ?
             AND portal_quote_mappings.idempotency_key = ?`,
          [input.ownerDomain, input.portalUserId, input.idempotencyKey],
        );
        if (existingRow) {
          const existing = mapMapping(existingRow);
          if (
            existing.requestFingerprint !== input.requestFingerprint
            || existing.customerCode !== input.customerCode
          ) throw new PortalQuoteIdempotencyConflictError();
          return existing;
        }

        const issueMonth = new Date(input.quotation.issueDate).toLocaleDateString("en-CA", {
          timeZone: "Asia/Tokyo",
        }).slice(0, 7).replace("-", "");
        const usedNumbers = await tx.all<{ quotation_number: string }>(
          "SELECT quotation_number FROM quotations WHERE quotation_number LIKE ?",
          [`KT-${issueMonth}-%`],
        );
        const quotationNumber = allocateQuotationNumber(usedNumbers, input.quotation.issueDate);
        const now = new Date().toISOString();
        const payloadJson = JSON.stringify(input.quotation.payload);
        const values = [
          quotationNumber,
          input.quotation.status,
          input.quotation.issueDate,
          input.quotation.validUntil,
          input.quotation.customerName,
          input.quotation.customerContact,
          input.quotation.productName,
          input.quotation.sizeSummary,
          input.quotation.quantity,
          input.quotation.fillingCostPerPiece,
          input.quotation.filmCostPerPiece,
          input.quotation.filmMeterPrice,
          input.quotation.filmOrderLengthM,
          input.quotation.targetMargin,
          input.quotation.taxRatePercent,
          input.quotation.pricePerPiece,
          input.quotation.subtotal,
          input.quotation.tax,
          input.quotation.grandTotal,
          input.quotation.deliveryDate,
          input.quotation.paymentTerms,
          input.quotation.notes,
          input.quotation.calculationVersion,
          input.quotation.resultHash,
          payloadJson,
          now,
          now,
          input.actorId,
          input.actorId,
        ];
        let quotationId: number;
        if (tx.dialect === "postgres") {
          const inserted = await tx.get<{ id: number }>(
            `${insertPortalQuotationSql()} RETURNING id`,
            values,
          );
          if (!inserted?.id) throw new Error("portal_quotation_insert_failed");
          quotationId = Number(inserted.id);
        } else {
          const inserted = await tx.run(insertPortalQuotationSql(), values);
          if (inserted.lastInsertRowid == null) throw new Error("portal_quotation_insert_failed");
          quotationId = Number(inserted.lastInsertRowid);
        }

        const publicId = randomUUID();
        const responseJson = JSON.stringify(input.buildResponse({
          publicId,
          quotationNumber,
        }));
        const insertedMapping = await tx.run(`
          INSERT INTO portal_quote_mappings (
            public_id,quotation_id,portal_user_id,owner_domain,customer_code,source,
            idempotency_key,request_fingerprint,response_json,created_at,updated_at
          ) VALUES (?,?,?,?,?,?,?,?,?,?,?)
        `, [
          publicId,
          quotationId,
          input.portalUserId,
          input.ownerDomain,
          input.customerCode,
          "customer_portal",
          input.idempotencyKey,
          input.requestFingerprint,
          responseJson,
          now,
          now,
        ]);
        if (Number(insertedMapping.changes) !== 1) throw new Error("portal_quote_mapping_insert_failed");
        const row = await tx.get<MappingRow>(
          `${mappingSelection()} WHERE portal_quote_mappings.public_id = ?`,
          [publicId],
        );
        if (!row) throw new Error("portal_quote_mapping_read_failed");
        return mapMapping(row);
      });
    } catch (error) {
      if (!isUniqueViolation(error)) throw error;
      const existing = await findPortalQuoteMapping({
        portalUserId: input.portalUserId,
        ownerDomain: input.ownerDomain,
        idempotencyKey: input.idempotencyKey,
      });
      if (existing) {
        if (
          existing.requestFingerprint !== input.requestFingerprint
          || existing.customerCode !== input.customerCode
        ) {
          throw new PortalQuoteIdempotencyConflictError();
        }
        return existing;
      }
    }
  }
  throw new Error("portal_quote_number_allocation_failed");
}
