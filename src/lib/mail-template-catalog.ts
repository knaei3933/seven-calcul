export const MAIL_TEMPLATE_CATEGORY_META = [
  { key: "all", label: "すべて" },
  { key: "workflow", label: "フィルム工作流" },
  { key: "customer", label: "顧客連携" },
  { key: "supplier", label: "サプライヤー" },
  { key: "portal", label: "ポータル" },
  { key: "system", label: "システム" },
] as const;

export function getMailTemplateCategory(key: string): Exclude<MailTemplateCategory, "all"> {
  if (key.startsWith("portal_")) return "portal";
  if (key === "mail_settings_test") return "system";
  if (key.startsWith("customer_")) return "customer";
  if (key === "film_purchase_order_supplier" || key === "film_reproof_request") return "supplier";
  return "workflow";
}

export function getMailTemplateCategoryLabel(key: string): string {
  const meta = MAIL_TEMPLATE_CATEGORY_META.find((item) => item.key === key);
  return meta?.label ?? "すべて";
}
