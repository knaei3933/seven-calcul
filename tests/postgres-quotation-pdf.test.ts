import { mkdtemp, rm } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { afterAll, beforeAll, describe, expect, it } from "vitest";
import type { Pool } from "pg";

const databaseUrl = process.env.POUCH_TEST_DATABASE_URL;
const databaseDirectory = await mkdtemp(join(tmpdir(), "postgres-quotation-pdf-"));
if (databaseUrl) {
  process.env.POUCH_QUOTATION_DB = join(databaseDirectory, "unused.sqlite");
  process.env.DATABASE_URL = databaseUrl;
  process.env.ADMIN_EMAIL = "pg-pdf-admin@integration.test";
  process.env.ADMIN_PASSWORD = "pg-pdf-admin-password";
  process.env.ADMIN_NAME = "PG PDF Admin";
}

// This test runs when CI/local infrastructure provides an isolated PostgreSQL database.
describe.skipIf(!databaseUrl)("PostgreSQL quotation PDF persistence", () => {
  let pool: Pool;

  beforeAll(async () => {
    const { Pool: PgPool } = await import("pg");
    pool = new PgPool({ connectionString: databaseUrl });
    await pool.query(`
      DROP TABLE IF EXISTS quotation_checklists CASCADE;
      DROP TABLE IF EXISTS quotations CASCADE;
      DROP TABLE IF EXISTS sessions CASCADE;
      DROP TABLE IF EXISTS users CASCADE;
      CREATE TABLE users (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        email TEXT NOT NULL UNIQUE,
        name TEXT NOT NULL,
        role TEXT NOT NULL CHECK(role IN ('admin','user')),
        is_active SMALLINT NOT NULL DEFAULT 1 CHECK(is_active IN (0,1)),
        password_hash TEXT NOT NULL,
        created_at TEXT NOT NULL,
        updated_at TEXT NOT NULL
      );
      INSERT INTO users (email,name,role,is_active,password_hash,created_at,updated_at)
      VALUES ('pg-pdf-admin@integration.test','PG PDF Admin','admin',1,'legacy','2026-01-01','2026-01-01');
      CREATE TABLE quotations (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        quotation_number TEXT NOT NULL UNIQUE,
        status TEXT NOT NULL CHECK(status IN ('draft','sent','approved','rejected','expired')),
        issue_date TEXT NOT NULL,
        valid_until TEXT NOT NULL,
        customer_name TEXT NOT NULL,
        customer_contact TEXT NOT NULL,
        product_name TEXT NOT NULL,
        size_summary TEXT NOT NULL,
        quantity TEXT NOT NULL,
        filling_cost_per_piece TEXT NOT NULL,
        film_cost_per_piece TEXT NOT NULL,
        film_meter_price TEXT NOT NULL,
        film_order_length_m TEXT NOT NULL,
        target_margin TEXT NOT NULL,
        tax_rate_percent TEXT NOT NULL,
        price_per_piece TEXT NOT NULL,
        subtotal TEXT NOT NULL,
        tax TEXT NOT NULL,
        grand_total TEXT NOT NULL,
        delivery_date TEXT NOT NULL,
        payment_terms TEXT NOT NULL,
        notes TEXT NOT NULL,
        calculation_version TEXT NOT NULL,
        result_hash TEXT NOT NULL,
        payload_json TEXT NOT NULL,
        created_at TEXT NOT NULL,
        updated_at TEXT NOT NULL,
        created_by INTEGER NOT NULL REFERENCES users(id),
        updated_by INTEGER REFERENCES users(id)
      );
      INSERT INTO quotations (
        quotation_number,status,issue_date,valid_until,customer_name,customer_contact,product_name,size_summary,
        quantity,filling_cost_per_piece,film_cost_per_piece,film_meter_price,film_order_length_m,target_margin,
        tax_rate_percent,price_per_piece,subtotal,tax,grand_total,delivery_date,payment_terms,notes,
        calculation_version,result_hash,payload_json,created_at,updated_at,created_by,updated_by
      ) VALUES (
        'S7-PG-PDF-001','draft','2026-01-02','2026-02-02','Legacy PG Customer','Legacy Contact','Legacy Pouch','60×80mm',
        '1000','4','1','200','500','0.4','10','20','20000','2000','22000','','','','legacy','legacy','{}',
        '2026-01-02T00:00:00.000Z','2026-01-02T00:00:00.000Z',1,1
      );
    `);
  });

  afterAll(async () => {
    const { closeDatabaseForTest } = await import("@/lib/auth-store");
    await closeDatabaseForTest();
    await pool?.end();
    await rm(databaseDirectory, { recursive: true, force: true });
  });

  it("migrates a legacy table and preserves exact binary bytes", { timeout: 120_000 }, async () => {
    const { getDatabaseForTest, getQuotationPdf, saveQuotationPdf } =
      await import("@/lib/quotation-store");
    const db = await getDatabaseForTest();
    expect(db.dialect).toBe("postgres");

    const columns = await db.all<{ column_name: string; data_type: string }>(`
      SELECT column_name, data_type
      FROM information_schema.columns
      WHERE table_schema = current_schema() AND table_name = 'quotations'
    `);
    const pdfColumns = new Map(columns.map((column) => [column.column_name, column.data_type]));
    expect(pdfColumns.get("pdf_data")).toBe("bytea");
    expect(pdfColumns.get("pdf_file_name")).toBe("text");
    expect(pdfColumns.get("pdf_uploaded_at")).toBe("text");
    expect(pdfColumns.get("pdf_sha256")).toBe("text");

    const legacy = await pool.query<{ quotation_number: string; customer_name: string }>(
      "SELECT quotation_number, customer_name FROM quotations WHERE quotation_number = $1",
      ["S7-PG-PDF-001"],
    );
    expect(legacy.rows).toEqual([{ quotation_number: "S7-PG-PDF-001", customer_name: "Legacy PG Customer" }]);

    const expectedPdf = Buffer.concat([
      Buffer.from("%PDF-", "latin1"),
      Buffer.from([0x00, 0x01, 0x7f, 0x80, 0xff]),
    ]);
    const fileName = "S7-PG-PDF-001-見積.pdf";
    await expect(saveQuotationPdf(1, expectedPdf, fileName)).resolves.toBe(true);
    const stored = await getQuotationPdf(1);
    expect(stored?.fileName).toBe(fileName);
    expect(stored?.data.equals(expectedPdf)).toBe(true);
    await expect(getQuotationPdf(999_999)).resolves.toBeNull();
  });
});
